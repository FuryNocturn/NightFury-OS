//! Datos de los glifos: trazos propios (diseño original de NightFury).
//! Unidades: y hacia arriba, línea base y=0, minúsculas 5, mayúsculas y cifras 7, descendentes hasta -2.
//! La tinta empieza en x=0 y `w` es su ancho.

pub enum S {
    /// Línea quebrada.
    L(&'static [(f32, f32)]),
    /// Arco de elipse: cx, cy, rx, ry, a0, a1 en grados (antihorario, 0 = derecha, 90 = arriba, a1 > a0).
    A(f32, f32, f32, f32, f32, f32),
    /// Punto.
    D(f32, f32),
}

pub struct Glyph {
    pub w: f32,
    pub s: &'static [S],
}

use S::{A, D, L};

/// Cuenco de las minúsculas redondas.
const CU: S = A(2.0, 2.5, 2.0, 2.5, 0.0, 360.0);
/// Cuerpo de la O mayúscula.
