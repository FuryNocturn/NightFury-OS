const P1: S = A(2.4, 5.1, 1.9, 1.9, -90.0, 90.0);

macro_rules! g {
    ($w:expr; $($s:expr),* $(,)?) => {
        Some(&Glyph { w: $w, s: &[$($s),*] })
    };
}

